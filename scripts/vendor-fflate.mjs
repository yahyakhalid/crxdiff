// Rebuilds src/vendor/fflate.js: only the raw DEFLATE decoder from fflate,
// tree-shaken so the vendored file has no Worker/Blob code paths.
// Usage: node scripts/vendor-fflate.mjs
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const pkg = JSON.parse(readFileSync('node_modules/fflate/package.json', 'utf8'));
const license = readFileSync('node_modules/fflate/LICENSE', 'utf8').trim();
const out = await build({
  stdin: { contents: "export { inflateSync } from 'fflate';", resolveDir: process.cwd() },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  write: false,
  treeShaking: true,
  legalComments: 'none',
});
const header = `// fflate ${pkg.version} (inflateSync only), https://github.com/101arrowz/fflate\n// Generated by scripts/vendor-fflate.mjs. Do not edit.\n/*\n${license}\n*/\n`;
writeFileSync('src/vendor/fflate.js', header + out.outputFiles[0].text);
console.log('wrote src/vendor/fflate.js', out.outputFiles[0].text.length, 'bytes');
